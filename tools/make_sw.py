#!/usr/bin/env python3
"""Write sw.js, the service worker that keeps the live build playable offline.

What it keeps: the entrance (index.html), the live build, every file under
assets/ that build names, the 講習 pages under minigames/, and the manifest
with its icons. Nothing else: an old build or a file the build no longer uses
is not kept, so the cache stays one build's worth however many releases go by.

The cache is named for the version and a hash of the files' bytes. When either
changes the worker changes, the browser installs it, and on activation every
other "labolic-game-" cache is deleted — so there is only ever one.

Usage:
  tools/make_sw.py            write sw.js for the build index.html points at
  tools/make_sw.py --check    exit 1 if sw.js is missing or out of date
"""
import hashlib, json, re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SKIP = {'assets/og-image.png'}          # a link-preview image; the game never shows it

def live_build():
    m = re.search(r'url=(labolic-playtest-(\d+)\.html)', (ROOT / 'index.html').read_text(encoding='utf-8'))
    if not m: sys.exit('error: index.html does not point at a build')
    return m.group(1), m.group(2)

def file_list(build):
    html = (ROOT / build).read_text(encoding='utf-8')
    assets = set(re.findall(r'assets/[A-Za-z0-9_/.-]+\.(?:png|webp|jpe?g|gif|svg)', html))
    man = json.loads((ROOT / 'manifest.webmanifest').read_text(encoding='utf-8'))
    assets |= {i['src'] for i in man.get('icons', [])}
    assets -= SKIP
    games = sorted(p.relative_to(ROOT).as_posix() for p in (ROOT / 'minigames').iterdir()
                   if p.suffix in ('.html', '.js', '.css'))
    files = ['./', 'index.html', build, 'manifest.webmanifest'] + sorted(assets) + games
    missing = [f for f in files if f != './' and not (ROOT / f).is_file()]
    if missing: sys.exit('error: missing ' + ', '.join(missing))
    return files

def render():
    build, ver = live_build()
    files = file_list(build)
    h = hashlib.sha256()
    for f in files:
        if f != './': h.update(f.encode()); h.update((ROOT / f).read_bytes())
    cache = f'labolic-game-v{ver}-{h.hexdigest()[:10]}'
    body = '\n'.join(f'  {json.dumps(f)},' for f in files)
    return f"""// GENERATED by tools/make_sw.py at release — do not edit by hand.
// Keeps the live build and its files so the game opens offline. Online, every
// request still goes to the network first (so an update shows at once) and
// refreshes the kept copy; offline, the kept copy answers.
const CACHE = '{cache}';
const PREFIX = 'labolic-game-';
const FILES = [
{body}
];
const SCOPE = new URL('./', self.location).pathname;
const KEPT = new Set(FILES.map(f => new URL(f, self.location).pathname));

self.addEventListener('install', e => {{
  e.waitUntil(caches.open(CACHE)
    .then(c => c.addAll(FILES.map(f => new Request(f, {{ cache: 'reload' }}))))
    .then(() => self.skipWaiting()));
}});

// One cache only: this release's. Older ones of ours go; nobody else's are touched.
self.addEventListener('activate', e => {{
  e.waitUntil(caches.keys()
    .then(keys => Promise.all(keys.filter(k => k.startsWith(PREFIX) && k !== CACHE).map(k => caches.delete(k))))
    .then(() => self.clients.claim()));
}});

self.addEventListener('fetch', e => {{
  const req = e.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  // Fonts, analytics, the leaderboard: the network's business, online or not.
  if (url.origin !== self.location.origin || !url.pathname.startsWith(SCOPE)) return;
  e.respondWith(fetch(req).then(res => {{
    if (res.ok && KEPT.has(url.pathname)) {{
      const copy = res.clone();
      caches.open(CACHE).then(c => c.put(url.pathname, copy));
    }}
    return res;
  }}).catch(() => caches.open(CACHE).then(c => c.match(url.pathname)).then(hit => {{
    if (hit) return hit;
    // A page that was never kept (an old build's URL) gets the entrance, which
    // sends it on to the live build.
    if (req.mode === 'navigate') return caches.match(new URL('index.html', self.location).href);
    return Response.error();
  }})));
}});
"""

def main():
    out = ROOT / 'sw.js'
    text = render()
    if '--check' in sys.argv:
        if not out.is_file() or out.read_text(encoding='utf-8') != text:
            print('STALE sw.js: run tools/make_sw.py'); sys.exit(1)
        print('OK   sw.js: matches the live build'); return
    out.write_text(text, encoding='utf-8')
    print(f'sw.js: {len(re.findall(chr(10) + "  \"", text))} files, cache {re.search(r"CACHE = .(.*?).;", text).group(1)}')

main()
